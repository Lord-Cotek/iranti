// Runs after `next build` (static export). Two jobs, in this order:
//
// 1. CSP: hash every inline <script> in each exported page and inject a per-page
//    <meta http-equiv="Content-Security-Policy"> as the first child of <head>. No inline
//    script runs unless it is one we shipped. (The Vercel header adds frame-ancestors etc.;
//    browsers enforce both policies.)
// 2. Service worker: write out/sw.js with a precache list of the app shell, versioned by a
//    hash of every precached file, so offline use works after one visit.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = new URL("../out/", import.meta.url).pathname;
// Same values Next inlined: .env.production fills anything the environment did not set.
const envFile = new URL("../.env.production", import.meta.url).pathname;
if (existsSync(envFile)) process.loadEnvFile(envFile);
const api = process.env.NEXT_PUBLIC_API_URL ?? "http://localhost:3001";
const storage = process.env.NEXT_PUBLIC_STORAGE_ORIGIN ?? "https://*.r2.cloudflarestorage.com";

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

const files = walk(OUT);

// ── 1. CSP ───────────────────────────────────────────────────────────────────
const inlineScript = /<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g;
let pages = 0;
for (const file of files.filter((f) => f.endsWith(".html"))) {
  let html = readFileSync(file, "utf8");
  if (html.includes('http-equiv="Content-Security-Policy"')) continue;
  const hashes = new Set();
  for (const m of html.matchAll(inlineScript)) {
    if (!m[1]) continue;
    hashes.add(`'sha256-${createHash("sha256").update(m[1], "utf8").digest("base64")}'`);
  }
  const policy = [
    "default-src 'self'",
    `script-src 'self' 'wasm-unsafe-eval' ${[...hashes].join(" ")}`.trim(),
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "font-src 'self'",
    `connect-src 'self' ${api} ${storage}`,
    "worker-src 'self'",
    "manifest-src 'self'",
    "base-uri 'self'",
    "form-action 'self'",
    "object-src 'none'",
  ].join("; ");
  html = html.replace(
    /<head>/,
    `<head><meta http-equiv="Content-Security-Policy" content="${policy}">`,
  );
  writeFileSync(file, html);
  pages++;
}

// ── 2. Service worker ───────────────────────────────────────────────────────
const shell = walk(OUT)
  .map((f) => "/" + relative(OUT, f).split(sep).join("/"))
  .filter(
    (p) => p !== "/sw.js" && !p.endsWith(".txt") && !p.startsWith("/fonts/IBMPlexSans-LICENSE"),
  )
  .map((p) => (p.endsWith("/index.html") ? p.slice(0, -"index.html".length) : p))
  .filter((p) => p !== "/404.html");
const version = createHash("sha256");
for (const f of walk(OUT).sort()) if (!f.endsWith("sw.js")) version.update(readFileSync(f));
const cacheName = `iranti-shell-${version.digest("hex").slice(0, 16)}`;

writeFileSync(
  join(OUT, "sw.js"),
  `// Generated by scripts/postbuild.mjs. App shell only: the vault itself is cached as
// ciphertext in IndexedDB by the app, never here. API and storage requests pass through.
const CACHE = ${JSON.stringify(cacheName)};
const SHELL = ${JSON.stringify(shell)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("iranti-shell-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

function pageKey(url) {
  let path = url.pathname;
  if (!path.endsWith("/") && !path.split("/").pop().includes(".")) path += "/";
  return path;
}

self.addEventListener("fetch", (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return;
  if (req.mode === "navigate") {
    // Network first so deploys arrive; the cached shell when offline.
    event.respondWith(
      fetch(req).catch(async () => (await caches.match(pageKey(url), { cacheName: CACHE })) ?? (await caches.match("/", { cacheName: CACHE })) ?? Response.error()),
    );
    return;
  }
  event.respondWith(caches.match(req, { cacheName: CACHE, ignoreSearch: true }).then((hit) => hit ?? fetch(req)));
});
`,
);
console.log(
  `postbuild: CSP injected into ${pages} pages; sw.js precaches ${shell.length} files (${cacheName})`,
);
